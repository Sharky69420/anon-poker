#!/usr/bin/env python3
"""Concatenate payout-worker.js + engine.js + bots.js into ONE deployable Cloudflare module worker.
usage: bundle.py [dir-with-the-three-files] [out-file]
engine.js and bots.js are wrapped in functions (their top-level names cannot collide with the worker's or each other);
the worker's own exports and `export default` stay (the deployed worker already exports helpers)."""
import os, re, sys
d = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(d, 'payout-worker.bundle.js')
rd = lambda n: open(os.path.join(d, n), encoding='utf-8').read()
EXP = re.compile(r'^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)', re.M)
def wrap(var, src):
    names = EXP.findall(src)
    m = re.search(r'^export\s*\{([^}]*)\}', src, re.M)
    if m: names += [x.strip().split(' as ')[0] for x in m.group(1).split(',') if x.strip()]
    if re.search(r'^export\s+default', src, re.M): sys.exit('bundle: %s has export default' % var)
    body = re.sub(r'^export\s*\{[^}]*\};?\s*$', '', src, flags=re.M)
    body = re.sub(r'^export\s+(?=(async\s+)?(function|const|let|class)\b)', '', body, flags=re.M)
    if re.search(r'^\s*import\s', body, re.M): sys.exit('bundle: %s has imports' % var)
    names = sorted(set(names))
    return 'const %s = (() => {\n%s\nreturn { %s };\n})();\n' % (var, body, ', '.join(names))
w = rd('payout-worker.js')
w2 = re.sub(r"^import \* as E from '\./engine\.js';\s*\n", '', w, flags=re.M)
w2 = re.sub(r"^import \* as BOT from '\./bots\.js';\s*\n", '', w2, flags=re.M)
if w2 == w or re.search(r'^import\s', w2, re.M): sys.exit('bundle: unexpected import lines in payout-worker.js')
# bots.js may itself import the engine (import * as E from './engine.js'): reuse the engine namespace
bots = re.sub(r"^import[^\n]*from\s+'\./engine\.js';\s*\n", '', rd('bots.js'), flags=re.M)
res = '// BUNDLE: payout-worker.js + engine.js + bots.js (generated by bundle.py; do not edit)\n' + wrap('E', rd('engine.js')) + wrap('BOT', bots) + w2
open(out, 'w', encoding='utf-8').write(res)
print('wrote', out, len(res), 'bytes')
