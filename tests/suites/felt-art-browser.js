// Real-browser test (Playwright Chromium) of the custom felt upload: hostile fixtures must be refused, clean ones rebuilt.
const path=require('path'),fs=require('fs');
module.exports=async function(){
let pass=0,fail=0;const ok=(n,c,d)=>{c?pass++:(fail++,console.log('  FAIL',n,d===undefined?'':d));};
let pw;try{pw=require('playwright');}catch(e){try{pw=require('/opt/npm-tools/node_modules/playwright');}catch(e2){}}
if(!pw){console.log('  (skipped: playwright not available)');return {name:'felt-art-browser.js (skipped)',pass:0,fail:0};}
const FX=process.env.FELT_FX||path.join(__dirname,'..','felt-fixtures');
const FXD=FX;
const PAGE=process.env.ZP_PAGE||path.join(__dirname,'..','..','app','index.html');
const browser=await pw.chromium.launch({args:['--no-sandbox']});
const ctx=await browser.newContext({viewport:{width:1280,height:800}});
const page=await ctx.newPage();
const net=[];page.on('request',r=>{const u=r.url();if(!/^(file|data|blob):/.test(u)&&!/fonts\.(googleapis|gstatic)/.test(u))net.push(u);});
const dialogs=[];page.on('dialog',d=>{dialogs.push(d.message());d.dismiss();});
const errs=[];page.on('pageerror',e=>errs.push(String(e)));
await page.route('**/*',r=>/^(file|data|blob):/.test(r.request().url())?r.continue():r.abort());
await page.goto('file://'+PAGE);
await page.waitForFunction(()=>typeof feltScan==='function');
const upload=async(name,mime)=>{
  const buf=fs.readFileSync(path.join(FXD,name));
  await page.evaluate(()=>{document.getElementById('feltOverlay').classList.add('show');});
  await page.setInputFiles('#feltFile',{name,mimeType:mime===undefined?'application/octet-stream':mime,buffer:buf});
  await page.waitForFunction(()=>!FELT_ART.busy,null,{timeout:30000});
  await page.waitForTimeout(50);
  return page.evaluate(()=>({url:FELT_ART.url,on:FELT_ART.on,log:document.getElementById('feltLog').innerText,bg:getComputedStyle(document.documentElement).getPropertyValue('--felt-bg')}));
};
const reset=async()=>{await page.evaluate(()=>{document.getElementById('feltRemove').click();});};
// ---- hostile / invalid: must be refused and change nothing
const BAD=[['evil-svg.svg','image/svg+xml'],['evil-svg-as.png','image/png'],['evil-html.jpg','image/jpeg'],['evil-png-trailer.png','image/png'],['evil-png-trailer-quiet.png','image/png'],['evil-jpg-trailer-quiet.jpg','image/jpeg'],
 ['evil-jpg-trailer.jpg','image/jpeg'],['evil-zip-trailer.jpg','image/jpeg'],['evil-png-text.png','image/png'],['evil-jpg-com.jpg','image/jpeg'],
 ['evil-jpg-utf16.jpg','image/jpeg'],['bad-crc.png','image/png'],['truncated.jpg','image/jpeg'],['bomb.png','image/png'],['huge-valid.png','image/png'],['toobig-valid.png','image/png'],['bad-crc-iend.png','image/png'],['bad-crc-ihdr.png','image/png'],['tiny.png','image/png'],
 ['empty.png','image/png'],['toobig.png','image/png'],['gif.png','image/png'],['pe.jpg','image/jpeg'],['anim.webp','image/webp'],['ok.jpg','image/png'] /* type mismatch */];
for(const [n,m] of BAD){
  if(!fs.existsSync(path.join(FXD,n)))continue; // very large fixtures are regenerated by felt-fixtures/make.py, not stored in the repo
  const r=await upload(n,m);
  ok('refused: '+n+(n==='ok.jpg'?' (declared as PNG)':''),r.url===null&&r.on===false&&!/felt-bg/.test('')&&!/data:image/.test(r.bg)&&/✕/.test(r.log),JSON.stringify({url:!!r.url,log:r.log.slice(0,120)}));
}
// ---- clean files: accepted, rebuilt, applied
for(const [n,m,k] of [['ok.png','image/png','png|webp|jpeg'],['ok.jpg','image/jpeg','webp|jpeg'],['ok.webp','image/webp','webp|jpeg'],['big-noise.jpg','image/jpeg','webp|jpeg']]){
  if(!fs.existsSync(path.join(FXD,n)))continue;
  await reset();const r=await upload(n,m);
  ok('accepted: '+n,!!r.url&&r.on&&/^data:image\/(webp|jpeg|png);base64,/.test(r.url)&&/data:image/.test(r.bg)&&/✓/.test(r.log)&&!/✕/.test(r.log),JSON.stringify({log:r.log.slice(0,200)}));
  if(r.url){
    const bytes=Buffer.from(r.url.split(',')[1],'base64');
    ok('rebuilt output is small and clean: '+n,bytes.length<=1500*1024&&!bytes.includes(Buffer.from('<script')),bytes.length);
    ok('rebuilt output is re-verified by the same gates: '+n,await page.evaluate(u=>{const b=atob(u.split(',')[1]),a=new Uint8Array(b.length);for(let i=0;i<b.length;i++)a[i]=b.charCodeAt(i);return feltCheckBytes(a,u.slice(5,u.indexOf(';'))).ok;},r.url));
  }
}
// ---- metadata is gone
await reset();
{const r=await upload('ok-exif.jpg','image/jpeg');
 ok('exif file accepted',!!r.url);
 if(r.url){const b=Buffer.from(r.url.split(',')[1],'base64');ok('exif/comment text does not survive the rebuild',!b.includes(Buffer.from('SECRET-MARKER-98765'))&&!b.includes(Buffer.from('ARTIST-MARKER-4321')));}}
// ---- applied to the real felt element
{const css=await page.evaluate(()=>{show('s-table');const f=document.getElementById('felt');return getComputedStyle(f).backgroundImage;});
 ok('felt-oval really paints the picture',/url\("data:image/.test(css),css.slice(0,80));
 const vis=await page.evaluate(()=>{const b=document.getElementById('feltOpenBtn');const r=b.getBoundingClientRect(),h=document.getElementById('djOpenBtn').getBoundingClientRect();return {w:r.width,h:r.height,onScreen:r.right<=innerWidth&&r.left>=0,sameRow:Math.abs(r.top-h.top)<4};});
 ok('header Felt button is visible, on screen, in the same row as DJ',vis.w>20&&vis.onScreen&&vis.sameRow,JSON.stringify(vis));}
// ---- keep / persistence
await page.evaluate(()=>{document.getElementById('feltKeep').checked=true;document.getElementById('feltKeep').dispatchEvent(new Event('change'));});
ok('keep on device stores sanitised art only',await page.evaluate(()=>{const s=JSON.parse(localStorage.getItem('zp-felt-art')||'null');return !!s&&FELT_URL_RE.test(s.url);}));
await page.reload();await page.waitForFunction(()=>typeof feltScan==='function');
ok('saved art is re-verified and re-applied after reload',await page.evaluate(()=>FELT_ART.on&&!!FELT_ART.url&&/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
// ---- not kept -> gone after reload
await page.evaluate(()=>{document.getElementById('feltKeep').checked=false;document.getElementById('feltKeep').dispatchEvent(new Event('change'));});
await page.reload();await page.waitForFunction(()=>typeof feltScan==='function');
ok('without Keep, nothing persists',await page.evaluate(()=>!FELT_ART.url&&localStorage.getItem('zp-felt-art')===null));
// ---- tampered storage is rejected
for(const [label,val] of [['svg data url',JSON.stringify({url:'data:image/svg+xml;base64,PHN2Zz48c2NyaXB0PmFsZXJ0KDEpPC9zY3JpcHQ+PC9zdmc+',dim:30,on:true})],
  ['png header + script',JSON.stringify({url:'data:image/png;base64,'+Buffer.concat([fs.readFileSync(path.join(FXD,'ok.png')),Buffer.from('<script>x</script>')]).toString('base64'),dim:30,on:true})],
  ['css injection',JSON.stringify({url:'data:image/png;base64,AAAA");background:url(http://evil.example/x)',dim:30,on:true})],
  ['garbage',"{not json"]]){
  await page.evaluate(v=>localStorage.setItem('zp-felt-art',v),val);
  await page.reload();await page.waitForFunction(()=>typeof feltScan==='function');
  ok('tampered storage ignored and cleared: '+label,await page.evaluate(()=>!FELT_ART.url&&!FELT_ART.on&&localStorage.getItem('zp-felt-art')===null&&!/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
}
// ---- last-line guard: a poisoned in-memory value can never reach CSS
{const r=await page.evaluate(()=>{const before=document.documentElement.style.getPropertyValue('--felt-bg');FELT_ART.url='data:image/png;base64,AAAA");background:url(http://evil.example/x)';FELT_ART.on=true;applyFelt(0);const after=document.documentElement.style.getPropertyValue('--felt-bg');FELT_ART.url=null;FELT_ART.on=false;applyFelt(0);return {inj:/evil\.example/.test(after)};});
 ok('a poisoned value never reaches the CSS variable',!r.inj,JSON.stringify(r));}
{const r=await page.evaluate(()=>['data:image/png;base64,AAAA");background:url(http://evil.example/x)','data:image/svg+xml;base64,AAAA','data:text/html;base64,AAAA','javascript:alert(1)','data:image/png;base64,AA AA','data:image/png;base64,AAAA\n','http://evil.example/a.png','data:image/gif;base64,AAAA'].map(u=>FELT_URL_RE.test(u)));
 ok('URL gate rejects injection, svg, html, remote and gif values',r.every(x=>x===false),JSON.stringify(r));
 ok('URL gate accepts a clean data URL',await page.evaluate(()=>FELT_URL_RE.test('data:image/webp;base64,UklGRg==')));}
// ---- preset pick turns art off; use toggle; dim; remove
await upload('ok.png','image/png');
await page.evaluate(()=>selectFelt(1));
ok('choosing a preset felt turns custom art off',await page.evaluate(()=>!FELT_ART.on&&!!FELT_ART.url&&!/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
await page.evaluate(()=>{const u=document.getElementById('feltUse');u.checked=true;u.dispatchEvent(new Event('change'));});
ok('Use toggle brings the art back',await page.evaluate(()=>FELT_ART.on&&/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
await page.evaluate(()=>{const d=document.getElementById('feltDim');d.value='60';d.dispatchEvent(new Event('input'));});
ok('Darken slider changes the overlay',await page.evaluate(()=>/rgba\(0, ?0, ?0, ?0\.60\)/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
await page.evaluate(()=>{show('s-lobby');applyFelt(P.feltId);});
ok('art survives applyFelt() calls made by the game (hand start etc.)',await page.evaluate(()=>/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
await reset();
ok('Remove restores the preset felt',await page.evaluate(()=>!FELT_ART.url&&!/data:image/.test(getComputedStyle(document.documentElement).getPropertyValue('--felt-bg'))));
// ---- global guarantees
ok('no network request left the page during all uploads',net.length===0,JSON.stringify(net.slice(0,3)));
ok('no script executed and no dialog opened',dialogs.length===0&&!(await page.evaluate(()=>!!window.__pwned)));
ok('no uncaught page errors',errs.length===0,JSON.stringify(errs.slice(0,2)));
await browser.close();
return {name:'felt-art-browser.js (real Chromium)',pass,fail};
};
